// Builds app/js/worldmap.js: country outlines (Natural Earth 1:110m via world-atlas, public domain / ISC) as SVG paths
// keyed by the country names bibliometrix uses. Equirectangular projection, 720 x 330 (latitudes 85N to 80S).
const tj = require('../vendor_src/topojson-client-3.1.0/package/dist/topojson-client.js');
const w = require('../vendor_src/world-atlas-2.0.2/package/countries-110m.json');
const fs = require('fs');
const fc = tj.feature(w, w.objects.countries);
const ALIAS = { 'UNITED STATES OF AMERICA': 'USA', 'DEM. REP. CONGO': 'CONGO', 'DOMINICAN REP.': 'DOMINICAN REPUBLIC', "CÔTE D'IVOIRE": "COTE D'IVOIRE",
  'CENTRAL AFRICAN REP.': 'CENTRAL AFRICAN REPUBLIC', 'EQ. GUINEA': 'EQUATORIAL GUINEA', 'ESWATINI': 'SWAZILAND', 'SOUTH KOREA': 'KOREA', 'SOLOMON IS.': 'SOLOMON ISLANDS',
  'CZECHIA': 'CZECH REPUBLIC', 'BOSNIA AND HERZ.': 'BOSNIA', 'S. SUDAN': 'SOUTH SUDAN', 'MACEDONIA': 'NORTH MACEDONIA', 'UNITED ARAB EMIRATES': 'U ARAB EMIRATES' };
const X = lon => +((lon + 180) * 2).toFixed(1), Y = lat => +((85 - lat) * 2).toFixed(1);
const ring = r => { let s = '', px, py; r.forEach((p, i) => { const x = X(p[0]), y = Y(Math.max(-80, p[1])); if (i && x === px && y === py) return; s += (i ? 'L' : 'M') + x + ' ' + y; px = x; py = y; }); return s + 'Z'; };
const out = {};
for (const f of fc.features) {
  let n = f.properties.name.toUpperCase(); if (n === 'ANTARCTICA' || n === 'FR. S. ANTARCTIC LANDS') continue;
  n = ALIAS[n] || n; const g = f.geometry; if (!g) continue;
  const polys = g.type === 'Polygon' ? [g.coordinates] : g.coordinates;
  out[n] = (out[n] || '') + polys.map(p => p.map(ring).join('')).join('');
}
const js = '/* World map outlines from Natural Earth 1:110m (public domain) via world-atlas 2.0.2 (ISC). Generated by build/make_map.js. */\n' +
  'window.ANCHOR_WORLD = { width: 720, height: 330, project: function (lon, lat) { return [(lon + 180) * 2, (85 - lat) * 2]; }, paths: ' + JSON.stringify(out) + ' };\n';
fs.writeFileSync(__dirname + '/../app/js/worldmap.js', js);
console.log(Object.keys(out).length, 'countries,', js.length, 'bytes');
