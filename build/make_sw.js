// Writes app/sw.js: an offline cache of every app file (the sample dataset is cached when first used).
const fs = require('fs'), path = require('path'), crypto = require('crypto');
const app = path.join(__dirname, '..', 'app'); const files = [];
(function walk(d) { for (const f of fs.readdirSync(d)) { const p = path.join(d, f); if (fs.statSync(p).isDirectory()) walk(p); else files.push(path.relative(app, p).split(path.sep).join('/')); } })(app);
const list = files.filter(f => f !== 'sw.js' && !f.startsWith('data/')).sort();
const h = crypto.createHash('sha256'); list.forEach(f => h.update(f).update(fs.readFileSync(path.join(app, f)))); const ver = h.digest('hex').slice(0, 12);
fs.writeFileSync(path.join(app, 'sw.js'), `/* ANCHOR Mobile offline cache ${ver} (generated by build/make_sw.js) */
const CACHE = 'anchor-${ver}';
const FILES = ${JSON.stringify(['./'].concat(list))};
self.addEventListener('install', e => { e.waitUntil(caches.open(CACHE).then(c => c.addAll(FILES)).then(() => self.skipWaiting())); });
self.addEventListener('activate', e => { e.waitUntil(caches.keys().then(ks => Promise.all(ks.filter(k => k.startsWith('anchor-') && k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim())); });
self.addEventListener('fetch', e => {
  const u = new URL(e.request.url); if (e.request.method !== 'GET' || u.origin !== location.origin) return;   // live services go straight to the network
  e.respondWith(caches.match(e.request, { ignoreSearch: true }).then(r => r || fetch(e.request).then(resp => { if (resp.ok && u.pathname.includes('/data/')) { const c = resp.clone(); caches.open(CACHE).then(ca => ca.put(e.request, c)); } return resp; })));
});
`);
console.log('sw.js', ver, list.length, 'files');
